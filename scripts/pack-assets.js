import fs from 'node:fs';
import path from 'node:path';

const dir = path.resolve('public/assets/vektor');
const files = fs.readdirSync(dir);
const map = {};
for (const f of files) {
  map[f] = fs.readFileSync(path.join(dir, f), 'utf8');
}
const out = `// Auto-generated by scripts/pack-assets.js
export const VEKTOR_ASSETS: Record<string, string> = ${JSON.stringify(map, null, 2)};
`;
fs.writeFileSync(path.resolve('src/lib/vektorAssets.ts'), out, 'utf8');
console.log('src/lib/vektorAssets.ts created successfully with', Object.keys(map).length, 'assets');
